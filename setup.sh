#!/usr/bin/env bash
# Quickstart for the Send to Phone Lightroom Classic plugin.
# Sets up everything: imsg CLI, config with your phone number, plugin
# installation, and the ⌥S keyboard shortcut.
set -euo pipefail

BOLD="$(tput bold 2>/dev/null || echo '')"
RESET="$(tput sgr0 2>/dev/null || echo '')"
PLUGIN_DIR="$(cd "$(dirname "$0")" && pwd)"
MODULES="$HOME/Library/Application Support/Adobe/Lightroom/Modules"
DOMAIN="com.adobe.LightroomClassicCC7"

echo "${BOLD}Send to Phone — quickstart${RESET}"

# 1. Phone number
echo
read -r -p "Phone number to send photos to (e.g. +15551234567): " NUMBER
if [ -z "$NUMBER" ]; then
    echo "A phone number is required." >&2
    exit 1
fi

cat > "$PLUGIN_DIR/Config.lua" <<EOF
-- Generated by setup.sh — not checked into git.
return {
    phone_number = "$NUMBER",
}
EOF
echo "Wrote Config.lua with your number."

# 2. imsg CLI
echo
if ! command -v imsg >/dev/null 2>&1; then
    if ! command -v brew >/dev/null 2>&1; then
        echo "Homebrew is required to install imsg. Install it from https://brew.sh and re-run." >&2
        exit 1
    fi
    echo "Installing imsg CLI (iMessage sender)..."
    brew install steipete/tap/imsg
else
    echo "imsg CLI already installed."
fi

# 3. Install plugin into Lightroom's Modules folder
echo
if pgrep -xq "Adobe Lightroom Classic"; then
    echo "Note: quit Lightroom Classic before restarting it at the end of setup."
fi
mkdir -p "$MODULES"
rm -rf "$MODULES/send-to-phone.lrdevplugin"
cp -R "$PLUGIN_DIR" "$MODULES/send-to-phone.lrdevplugin"
echo "Installed plugin to $MODULES/send-to-phone.lrdevplugin"

# 4. Keyboard shortcut (⌥S)
# Lightroom indents Plug-in Extras items with three spaces; bind both spellings.
defaults write "$DOMAIN" NSUserKeyEquivalents -dict \
    "Send to Phone" '~s' \
    "   Send to Phone" '~s'
echo "Bound ⌥S to 'Send to Phone'."

# 5. Permissions reminders
echo
echo "${BOLD}Two one-time manual steps:${RESET}"
echo "  1. System Settings > Privacy & Security > ${BOLD}Full Disk Access${RESET}: enable for ${BOLD}Lightroom Classic${RESET}"
echo "     (required for imsg to stage attachments in ~/Library/Messages)"
echo "  2. First run: approve the Automation prompts (Lightroom Classic > Messages)"
echo
echo "${BOLD}Done. Quit and relaunch Lightroom Classic, select a photo, press ⌥S.${RESET}"
